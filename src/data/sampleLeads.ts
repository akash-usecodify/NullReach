export function getSampleCsvString(): string {
  const headers = [
    'Full Name',
    'Job Title',
    'Company',
    'Industry Category',
    'Email',
    'Phone',
    'Location',
    'Country',
    'Website',
    'Revenue Range',
    'Employees',
    'LinkedIn',
    'Google Business URL',
    'Google Rating',
    'Google Reviews',
    'Twitter',
    'Facebook',
    'Instagram',
    'YouTube',
    'GitHub',
    'Logo URL',
    'Notes'
  ];

  const rows = INITIAL_LEADS.map(lead => [
    `"${lead.name.replace(/"/g, '""')}"`,
    `"${lead.title.replace(/"/g, '""')}"`,
    `"${lead.company.replace(/"/g, '""')}"`,
    `"${lead.category.replace(/"/g, '""')}"`,
    `"${lead.email.replace(/"/g, '""')}"`,
    `"${lead.phone.replace(/"/g, '""')}"`,
    `"${lead.location.replace(/"/g, '""')}"`,
    `"${(lead.country || '').replace(/"/g, '""')}"`,
    `"${(lead.website || '').replace(/"/g, '""')}"`,
    `"${(lead.revenue || '').replace(/"/g, '""')}"`,
    `"${(lead.employees || '').replace(/"/g, '""')}"`,
    `"${(lead.linkedin || '').replace(/"/g, '""')}"`,
    `"${(lead.googleBusinessUrl || '').replace(/"/g, '""')}"`,
    `"${lead.googleRating || ''}"`,
    `"${lead.googleReviewsCount || ''}"`,
    `"${(lead.socials?.twitter || '').replace(/"/g, '""')}"`,
    `"${(lead.socials?.facebook || '').replace(/"/g, '""')}"`,
    `"${(lead.socials?.instagram || '').replace(/"/g, '""')}"`,
    `"${(lead.socials?.youtube || '').replace(/"/g, '""')}"`,
    `"${(lead.socials?.github || '').replace(/"/g, '""')}"`,
    `"${(lead.logoUrl || '').replace(/"/g, '""')}"`,
    `"${(lead.notes || '').replace(/"/g, '""')}"`,
  ].join(','));

  return [headers.join(','), ...rows].join('\n');
}
